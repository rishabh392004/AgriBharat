const I18nContext = createContext<{
  locale: Locale
  setLocale: (locale: Locale) => void
  t: (key: string, vars?: Record<string, string | number>) => string
}>({
  locale: 'en',
  setLocale: () => {},
  t: (key) => en[key] || key,
})

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>('en')

  useEffect(() => {
    const saved = window.localStorage.getItem('kr-locale') as Locale | null
    if (saved && saved in localeLabels) setLocaleState(saved)
  }, [])

  const setLocale = (next: Locale) => {
    setLocaleState(next)
    window.localStorage.setItem('kr-locale', next)
  }

  const value = useMemo(
    () => ({
      locale,
      setLocale,
      t: (key: string, vars?: Record<string, string | number>) => {
        let text = translations[locale][key] || en[key] || key
        if (vars) {
          for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, String(v))
        }
        return text
      },
    }),
    [locale],
  )

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export const useI18n = () => useContext(I18nContext)
